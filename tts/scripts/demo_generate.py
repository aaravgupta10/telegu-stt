#!/usr/bin/env python3
"""Render a list of Telugu sentences with the fine-tuned model and build an offline demo page.

STATUS: written 2026-10-19, syntax-checked only, never run. Run it on the notebook (CPU is enough):
  cd ~/SageMaker/tts/pocket-tts && source ~/SageMaker/tts/env.sh && \
  uv run python ~/SageMaker/tts/scripts/demo_generate.py --sentences ~/SageMaker/tts/demo_sentences.txt --out ~/SageMaker/tts/demo_out

Input: a UTF-8 text file, one Telugu sentence per line, ONE sentence per line (the model must be given one sentence at a time).
Digits are not supported (the model never saw numbers); lines containing digits or Latin letters are skipped and reported.
Voices: by default one SYSPIN male and one SYSPIN female clip (the ones used in the evaluation). Output: out/audio/*.wav and out/index.html.
"""
import argparse
import html
import os
import re
import subprocess
import sys
import wave
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HOME = os.path.expanduser("~/SageMaker/tts")
MALE = f"{HOME}/data/full_Male/wavs/IISc_SYSPINProject_te_m_BOOK_10500.wav"
FEMALE = f"{HOME}/data/full_Female/wavs/IISc_SYSPINProject_te_f_AGRI_00216.wav"
BAD = re.compile("[0-9" + chr(0x0C66) + "-" + chr(0x0C6F) + "]|[A-Za-z]")  # ASCII digits, Telugu digits, Latin letters


def make_cfg(tokenizer_json, out_path):
    import yaml
    c = yaml.safe_load(open("pocket_tts/config/english_2026-04_24l.yaml"))
    c["flow_lm"]["lookup_table"]["tokenizer_path"] = tokenizer_json
    yaml.safe_dump(c, open(out_path, "w"), sort_keys=False)
    return str(out_path)


def gen(job):
    cfg, ckpt, voice, text, out, device = job
    env = dict(os.environ, OMP_NUM_THREADS="4", MKL_NUM_THREADS="4")
    cmd = ["pocket-tts", "generate", "--config", cfg, "--checkpoint", ckpt, "--voice", voice, "--text", text,
           "--output-path", out, "--device", device, "-q"]
    r = subprocess.run(cmd, capture_output=True, text=True, env=env)
    ok = r.returncode == 0 and Path(out).exists()
    return out, ok, ("" if ok else r.stderr[-300:])


def secs(p):
    with wave.open(p) as w:
        return round(w.getnframes() / w.getframerate(), 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sentences", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--checkpoint", default=f"{HOME}/runs/telugu_full/checkpoint_00015000.pt")
    ap.add_argument("--tokenizer", default=f"{HOME}/data/full/tokenizer.json")
    ap.add_argument("--male", default=MALE)
    ap.add_argument("--female", default=FEMALE)
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--workers", type=int, default=8)
    a = ap.parse_args()

    out = Path(os.path.expanduser(a.out)); (out / "audio").mkdir(parents=True, exist_ok=True)
    cfg = make_cfg(os.path.expanduser(a.tokenizer), out / "gen.yaml")
    lines = [l.strip() for l in open(os.path.expanduser(a.sentences), encoding="utf-8") if l.strip()]
    keep, skipped = [], []
    for l in lines:
        (skipped if BAD.search(l) else keep).append(l)
    for l in skipped:
        print("SKIPPED (digits or Latin letters are not supported):", l)
    print(f"rendering {len(keep)} sentences x 2 voices = {2 * len(keep)} clips on {a.device} ...", flush=True)

    jobs, names = [], []
    for i, t in enumerate(keep):
        for tag, v in (("m", a.male), ("f", a.female)):
            o = str(out / "audio" / f"s{i:02d}_{tag}.wav")
            jobs.append((cfg, os.path.expanduser(a.checkpoint), v, t, o, a.device)); names.append((i, tag))
    with ThreadPoolExecutor(max_workers=a.workers) as ex:
        res = list(ex.map(gen, jobs))
    bad = [(o, e) for o, ok, e in res if not ok]
    print(f"done: {len(jobs) - len(bad)} ok, {len(bad)} failed")
    for o, e in bad[:3]:
        print("FAILED", o, e.replace("\n", " | "))

    rows = []
    for i, t in enumerate(keep):
        cells = []
        for tag in ("m", "f"):
            p = out / "audio" / f"s{i:02d}_{tag}.wav"
            cells.append('<td><audio controls preload="none" src="audio/%s"></audio><div class="d">%ss</div></td>' % (p.name, secs(str(p))) if p.exists() else "<td>failed</td>")
        rows.append('<tr><td class="n">%d</td><td class="t" lang="te">%s</td>%s</tr>' % (i + 1, html.escape(t), "".join(cells)))
    page = ("<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'><title>Telugu TTS demo</title>"
            "<style>body{font:16px/1.5 system-ui,'Nirmala UI',sans-serif;margin:24px auto;max-width:980px;padding:0 16px}td,th{border-bottom:1px solid #ddd;padding:8px 6px;text-align:left}"
            ".t{font-size:1.12rem}.n,.d{color:#777;font-size:.8rem}audio{width:230px}</style></head><body><h1>Telugu text-to-speech: prototype</h1>"
            "<p>Pre-generated by our fine-tuned model, one sentence at a time. Male and female reference voice.</p><table><thead><tr><th>#</th><th>Sentence</th><th>Male</th><th>Female</th></tr></thead><tbody>"
            + "".join(rows) + "</tbody></table></body></html>")
    (out / "index.html").write_text(page, encoding="utf-8")
    print("wrote", out / "index.html")


if __name__ == "__main__":
    main()
